    private void configurarTabla() {
    DefaultTableModel modelo =
            new DefaultTableModel(
                    new Object[]{
                        "ID",
                        "Titulo",
                        "Autor",
                        "Categoria",
                        "Año",
                        "Editorial"
                    },
                    0
            ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };
    tblLibros.setModel(modelo);
}
private void cargarLibros() {
    DefaultTableModel modelo =
            (DefaultTableModel) tblLibros.getModel();
    modelo.setRowCount(0);
    String sql =
            "SELECT id, titulo, autor, categoria, anio, editorial "
            + "FROM Libro "
            + "ORDER BY id";
    try (
        Connection cn = Conexion.Conectar();
        PreparedStatement ps = cn.prepareStatement(sql);
        ResultSet rs = ps.executeQuery()
    ) {
        while (rs.next()) {
            Object[] fila = {
                rs.getInt("id"),
                rs.getString("titulo"),
                rs.getString("autor"),
                rs.getString("categoria"),
                rs.getInt("anio"),
                rs.getString("editorial")
            };
            modelo.addRow(fila);
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Error al consultar:\n" + e.getMessage()
        );
    }
}
private void limpiar() {
    txtTitulo.setText("");
    txtAutor.setText("");
    txtCategoria.setText("");
    txtAnio.setText("");
    tblLibros.clearSelection();
    txtTitulo.requestFocus();
    txtEditorial.setText("");
}

private boolean validarCampos() {
    if (txtTitulo.getText().trim().isEmpty()
            || txtAutor.getText().trim().isEmpty()
            || txtCategoria.getText().trim().isEmpty()
            || txtAnio.getText().trim().isEmpty()
            || txtEditorial.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Todos los campos son obligatorios."
        );
        return false;
    }
    try {
        int anio =
                Integer.parseInt(txtAnio.getText().trim());
        if (anio <= 0) {
                        
            JOptionPane.showMessageDialog(
                    this,
                    "El año debe ser válido."
            );
            return false;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(
                this,
                "El año debe ser numérico."
        );
        return false;
    }
    return true;
}
