    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
            int fila = tblLibros.getSelectedRow();
    if (fila == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Seleccione un libro."
        );
        return;
    }
    if (!validarCampos()) {
        return;
    }
    int id =
            Integer.parseInt(tblLibros.getValueAt(fila, 0).toString()
            );
                    
    String titulo = txtTitulo.getText().trim();
    String autor = txtAutor.getText().trim();
    String categoria = txtCategoria.getText().trim();
    int anio =
            Integer.parseInt(
                    txtAnio.getText().trim()
            );
    String editorial = txtEditorial.getText().trim();
    String sql =
            "UPDATE Libro "
            + "SET titulo=?, autor=?, categoria=?, anio=?, editorial=? "
            + "WHERE id=?";
    try (
        Connection cn = Conexion.Conectar();
        PreparedStatement ps = cn.prepareStatement(sql)
    ) {
        ps.setString(1, titulo);
        ps.setString(2, autor);
        ps.setString(3, categoria);
        ps.setInt(4, anio);
        ps.setString(5, editorial);
        ps.setInt(6, id);
        ps.executeUpdate();
        JOptionPane.showMessageDialog(
                this,
                "Libro modificado correctamente."
        );
        cargarLibros();
        limpiar();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Error al modificar:\n" + e.getMessage()
        );
    }
    }//GEN-LAST:event_btnModificarActionPerformed

